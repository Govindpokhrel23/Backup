// ============================================================
// lib/local-data.js — このスマホに残したデータを消す
// ------------------------------------------------------------
// このファイルは、ログアウトした時に、このスマホ（ブラウザ）に残した
// アプリのデータを消すためのファイルです（2026年11月16日・セキュリティ）。
//
// なぜ必要か：お店のタブレットなど、みんなで使う機械でログアウトしたあと、
//   次の人に前の人のシフトや下書きが見えないようにするため。
// 消すもの：名前が "shiftapp-" で始まるもの（自分のシフトの控え・AIの設定・下書きの記録など）
// 残すもの：見本版のデータ（shiftapp-mock-…。サーバーにつながない練習用）
// ============================================================

/** ログアウトの時に、このスマホに残したアプリのデータを消す */
export function clearLocalData() {   // スマホのデータを消す関数
  try {   // 消せない機械でも止めない
    const keys = [];   // 消す名前
    for (let index = 0; index < localStorage.length; index++) {   // 保存してあるものを1つずつ
      const key = localStorage.key(index);   // 名前
      if (key && key.startsWith("shiftapp-") && !key.startsWith("shiftapp-mock-")) keys.push(key);   // アプリのもの（見本版はのぞく）
    }
    keys.forEach((key) => localStorage.removeItem(key));   // まとめて消す
    sessionStorage.clear();   // 一時的に覚えたものも消す
  } catch { /* プライベートブラウズなどで使えない時は何もしない */ }
}
