// ============================================================
// store.js — アプリ全体で共有する「今の状態」
// ------------------------------------------------------------
// ・ログイン中の人（user）など、どの画面からも使う情報をここに置く
// ・画面ごとの細かい状態は、それぞれの画面ファイルの中に持つ
// ============================================================

export const state = {
  /** ログイン中の店員（店長も含む）。ログインしていなければ null */
  user: null,
};

/** 店長かどうか */
export function isManager() {
  return state.user?.role === "manager";
}
